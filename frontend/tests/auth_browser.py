import uuid
from playwright.sync_api import sync_playwright, expect

def check_auth(url):
    with sync_playwright() as p:
        browser = p.chromium.launch()
        try:
            page = browser.new_page(viewport={'width':390, 'height':900})
            email = 'auth-' + uuid.uuid4().hex + '@example.com'
            password = 'browser test passphrase'
            page.route('**/auth/me', lambda route: route.abort())
            page.goto(url)
            expect(page.get_by_role('alert')).to_have_text('Could not check your session.')
            page.unroute('**/auth/me')
            page.get_by_role('button', name='Retry session').click()
            expect(page).to_have_url(url + '/login')
            expect(page.get_by_role('heading', name='Welcome back')).to_be_focused()
            expect(page.get_by_role('link', name='Catalog')).to_have_count(0)
            page.get_by_role('link', name='Create an account').click()
            expect(page).to_have_url(url + '/register')
            page.go_back()
            expect(page).to_have_url(url + '/login')
            page.go_forward()
            page.reload()
            expect(page.get_by_label('Password')).to_have_attribute('autocomplete', 'new-password')
            page.get_by_label('Email', exact=True).fill(email)
            page.get_by_label('Password', exact=True).fill(password)
            page.get_by_role('button', name='Create account', exact=True).click()
            expect(page).to_have_url(url + '/login?registered=1')
            expect(page.get_by_role('status')).to_contain_text('Account created.')
            assert page.request.get(url + '/auth/me').status == 401
            page.get_by_role('link', name='Create an account').click()
            page.get_by_label('Email', exact=True).fill(email)
            page.get_by_label('Password', exact=True).fill(password)
            page.get_by_role('button', name='Create account', exact=True).click()
            expect(page.get_by_role('alert')).to_contain_text('already has an account')
            page.get_by_role('link', name='I already have an account').click()
            page.get_by_label('Email', exact=True).fill(email)
            page.get_by_label('Password', exact=True).fill('wrong password')
            page.get_by_role('button', name='Sign in', exact=True).click()
            expect(page.get_by_role('alert')).to_have_text('Incorrect email or password.')
            page.get_by_label('Password', exact=True).fill(password)
            held=[]
            page.route('**/auth/login', lambda route: held.append(route))
            with page.expect_request('**/auth/login'):
                page.get_by_role('button', name='Sign in', exact=True).click()
            expect(page.get_by_role('button', name='Please wait…')).to_be_disabled()
            assert held[0].request.headers.get('x-csrf-token')
            held[0].continue_()
            page.unroute('**/auth/login')
            expect(page).to_have_url(url + '/')
            expect(page.get_by_role('heading', name='My library', exact=True)).to_be_visible()
            expect(page.get_by_text('Your library is empty.', exact=False)).to_be_visible()
            page.reload()
            expect(page.get_by_text(email, exact=True)).to_be_visible()
            page.goto(url + '/login')
            expect(page).to_have_url(url + '/')
            page.get_by_role('button', name='Sign out', exact=True).click()
            expect(page).to_have_url(url + '/login')
            expect(page.get_by_role('button', name='Add a book', exact=True)).to_have_count(0)
            page.goto(url + '/library')
            expect(page).to_have_url(url + '/login')
            assert page.evaluate('localStorage.length === 0 && sessionStorage.length === 0')
            print('PASS: login-first routing, registration, duplicate email, failed/pending login, history, session reload and logout')
        finally:
            browser.close()
