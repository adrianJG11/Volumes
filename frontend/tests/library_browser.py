import uuid
from playwright.sync_api import sync_playwright, expect

def check_library(url):
    password = 'library browser passphrase'
    title = 'Library journey ' + uuid.uuid4().hex[:8]
    with sync_playwright() as p:
        browser = p.chromium.launch()
        try:
            pages = []
            for index in range(2):
                page = browser.new_page(viewport={'width': 390 if index == 0 else 1440, 'height': 900})
                email = 'library-' + uuid.uuid4().hex + '@example.com'
                page.goto(url + '/register')
                page.get_by_label('Email', exact=True).fill(email)
                page.get_by_label('Password', exact=True).fill(password)
                page.get_by_role('button', name='Create account', exact=True).click()
                expect(page).to_have_url(url + '/login?registered=1')
                page.get_by_label('Email', exact=True).fill(email)
                page.get_by_label('Password', exact=True).fill(password)
                page.get_by_role('button', name='Sign in', exact=True).click()
                expect(page).to_have_url(url + '/')
                page.get_by_role('link', name='My library', exact=True).click()
                expect(page.get_by_text('No books in your library yet.', exact=False)).to_be_visible()
                page.get_by_role('link', name='Catalog', exact=True).click()
                if index == 0:
                    page.get_by_role('button', name='Add a book', exact=True).click()
                    page.get_by_label('Title', exact=True).fill(title)
                    page.get_by_label('Author', exact=True).fill('Test author')
                    page.get_by_label('Genre', exact=True).fill('Fiction')
                    page.get_by_label('Pages', exact=True).fill('120')
                    page.get_by_role('button', name='Add to catalog').click()
                add = page.get_by_role('button', name='Add ' + title + ' to my library', exact=True)
                add.click()
                expect(page.get_by_text('In your library.', exact=False)).to_be_visible()
                page.reload()
                add.click()
                expect(page.get_by_text('In your library.', exact=False)).to_be_visible()
                page.get_by_role('link', name='My library', exact=True).click()
                expect(page.get_by_role('heading', name=title, exact=True)).to_have_count(1)
                expect(page.get_by_text('Saved rating: Not rated', exact=True)).to_be_visible()
                page.get_by_role('combobox').select_option(str(5 - index * 3))
                page.get_by_role('button', name='Save rating', exact=True).click()
                expect(page.get_by_text('Rating saved.', exact=True)).to_be_visible()
                page.reload()
                expect(page.get_by_text('Saved rating: ' + str(5 - index * 3) + ' / 5')).to_be_visible()
                assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
                pages.append(page)
            alice, bob = pages
            alice.reload()
            expect(alice.get_by_text('Saved rating: 5 / 5')).to_be_visible()
            alice.route('**/rating', lambda route: route.fulfill(status=503, json={}))
            alice.get_by_role('combobox').select_option('4')
            alice.get_by_role('button', name='Save rating', exact=True).click()
            expect(alice.get_by_role('alert')).to_contain_text('saved rating has not changed')
            expect(alice.get_by_text('Saved rating: 5 / 5')).to_be_visible()
            alice.unroute('**/rating')
            alice.get_by_role('button', name='Save rating', exact=True).click()
            expect(alice.get_by_text('Saved rating: 4 / 5')).to_be_visible()
            alice.get_by_role('button', name='Clear rating', exact=True).click()
            expect(alice.get_by_text('Rating cleared.', exact=True)).to_be_visible()
            alice.reload()
            expect(alice.get_by_text('Saved rating: Not rated')).to_be_visible()
            expect(alice.get_by_role('heading', name=title, exact=True)).to_be_visible()
            bob.reload()
            expect(bob.get_by_text('Saved rating: 2 / 5')).to_be_visible()
            alice.route('**/me/library', lambda route: route.fulfill(status=503, json={}))
            alice.reload()
            expect(alice.get_by_role('alert')).to_have_text('Could not load your library.')
            alice.unroute('**/me/library')
            alice.get_by_role('button', name='Retry library').click()
            expect(alice.get_by_text('Saved rating: Not rated')).to_be_visible()
            alice.get_by_role('link', name='Catalog', exact=True).click()
            expect(alice.get_by_role('heading', name=title, exact=True)).to_be_visible()
            alice.get_by_role('link', name='My library', exact=True).click()
            expect(alice.get_by_role('combobox')).to_be_visible()
            alice.context.clear_cookies()
            alice.get_by_role('combobox').select_option('3')
            alice.get_by_role('button', name='Save rating', exact=True).click()
            expect(alice.get_by_role('heading', name=title, exact=True)).to_have_count(0)
            expect(alice.get_by_role('combobox')).to_have_count(0)
            bob.get_by_role('button', name='Sign out', exact=True).click()
            expect(bob.get_by_role('combobox')).to_have_count(0)
            print('PASS: two private libraries, duplicate add, save/edit/clear/reload, failed save/retry and session expiry')
        finally:
            browser.close()
